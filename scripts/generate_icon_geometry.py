"""Generate native stroke lengths from the locked Lucide icon definitions.

Run after npm ci with svg.path installed in the project's developer venv.
"""
import json
import math
from pathlib import Path
import re
import subprocess

from svg.path import parse_path

ROOT = Path(__file__).resolve().parents[1]
ICONS = {
    'Today': 'sun', 'Partner': 'messages-square', 'Work': 'briefcase',
    'Reviews': 'clipboard-list', 'Website': 'globe', 'Activity': 'activity',
    'Organization': 'building-complex', 'Account': 'circle-user-round',
    'Settings': 'sliders-horizontal', 'Help': 'circle-question-mark', 'new': 'square-pen',
    'search': 'search', 'pin': 'pin', 'More': 'layout-grid', 'send': 'arrow-up',
    'back': 'arrow-left', 'menu': 'menu', 'close': 'x', 'forward': 'chevron-right',
    'down': 'chevron-down', 'reset': 'rotate-ccw', 'Notifications': 'bell',
    'Privacy': 'shield', 'Appearance': 'palette', 'About': 'info', 'preview': 'flask-conical',
    'members': 'users-round', 'checklist': 'clipboard-list', 'plus': 'plus', 'check': 'check',
    'up': 'chevron-up', 'image': 'image', 'file': 'file-text', 'offline': 'wifi-off',
    'loading': 'loader-circle', 'warning': 'triangle-exclamation-point', 'signout': 'log-out',
    'email': 'mail', 'key': 'key-round', 'clock': 'clock', 'download': 'download',
}


def stroke_length(kind, attrs):
    def number(name, default=0):
        return float(attrs.get(name, default))

    if kind == 'path':
        return parse_path(attrs['d']).length()
    if kind == 'circle':
        return math.tau * number('r')
    if kind == 'rect':
        width, height = number('width'), number('height')
        radius = min(number('rx', attrs.get('ry', 0)), width / 2, height / 2)
        return 2 * (width + height) + (math.tau - 8) * radius
    if kind == 'line':
        return math.hypot(number('x2') - number('x1'), number('y2') - number('y1'))
    if kind in ('polygon', 'polyline'):
        coords = [float(n) for n in re.findall(r'-?\d+(?:\.\d+)?', attrs['points'])]
        points = list(zip(coords[::2], coords[1::2]))
        if kind == 'polygon':
            points.append(points[0])
        return sum(math.dist(a, b) for a, b in zip(points, points[1:]))
    if kind == 'ellipse':
        a, b = number('rx'), number('ry')
        return math.pi * (3 * (a + b) - math.sqrt((3 * a + b) * (a + 3 * b)))
    raise ValueError(f'Unhandled Lucide element {kind}')


def read_nodes(names):
    script = """
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.dirname(require.resolve('lucide-react-native'));
const icons = process.argv.slice(1).map(name => {
    const source = fs.readFileSync(path.join(root, 'icons', name + '.js'), 'utf8');
    const literal = source.split('const __iconData = ')[1].split(';\\nconst __iconNode')[0];
    return vm.runInNewContext('(' + literal + ')', {}, {timeout: 100}).node;
});
process.stdout.write(JSON.stringify(icons));
"""
    values = json.loads(subprocess.check_output(['node', '-e', script, *names], cwd=ROOT))
    return dict(zip(names, values))


names = list(dict.fromkeys(ICONS.values()))
nodes = read_nodes(names)
symbols = {name: 'icon' + ''.join(part.title() for part in name.split('-')) for name in names}
lines = [
    '// Generated by scripts/generate_icon_geometry.py from the locked Lucide package.',
    '// Strokes render the original Lucide SVG attributes. Lengths are used only for drawing motion.',
    *[f"import {{__iconData as {symbols[name]}}} from 'lucide-react-native/icons/{name}';" for name in names],
    '', 'export const iconGeometry={',
]
for alias, name in ICONS.items():
    lengths = [round(max(.1, stroke_length(kind, attrs)), 2) for kind, attrs, *_ in nodes[name]]
    lines.append(f' {alias}:{{data:{symbols[name]},lengths:{json.dumps(lengths)}}},')
lines.append('} as const;')
(ROOT / 'src/iconGeometry.ts').write_text('\n'.join(lines) + '\n')
